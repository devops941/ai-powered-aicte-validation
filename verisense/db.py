def get_application(application_no: str, db_path: str = DB_PATH) -> Optional[Dict[str, Any]]:
    """Fetches application details joining institution metadata."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        """
        SELECT a.*, i.name as institution_name, i.aicte_id, i.state, i.city, i.address
        FROM applications a
        JOIN institutions i ON a.institution_id = i.id
        WHERE a.application_no = ?
        """,
        (application_no,)
    )
    row = cursor.fetchone()
    conn.close()
    return dict(row) if row else None


