def get_flags_summary(db_path: str = DB_PATH) -> List[Dict[str, Any]]:
    """Aggregates all flagged rules and counts across the application database."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        """
        SELECT rule_id, issue, severity, COUNT(*) as count
        FROM flags
        GROUP BY rule_id, issue, severity
        ORDER BY count DESC
        """
    )
    rows = [dict(row) for row in cursor.fetchall()]
    conn.close()
    return rows


