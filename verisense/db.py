# --- FLAGS ---

def insert_flag(application_id: int, rule_id: str, severity: str, issue: str, evidence: str,
                document_id: Optional[int] = None, doc_type: Optional[str] = None, db_path: str = DB_PATH) -> int:
    """
    Inserts a rule violation or check flag.
    HARD RULE: Every flag must record issue, document, rule ID, evidence, and timestamp.
    """
    now = datetime.now().isoformat(timespec="seconds")
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        """
        INSERT INTO flags (application_id, document_id, doc_type, rule_id, severity, issue, evidence, flagged_at)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?)
        """,
        (application_id, document_id, doc_type, rule_id, severity, issue, evidence, now)
    )
    conn.commit()
    flag_id = cursor.lastrowid
    conn.close()
    return flag_id


def get_flags_by_application(application_id: int, db_path: str = DB_PATH) -> List[Dict[str, Any]]:
    """Fetches all flags raised against an application with document type info."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute(
        """
        SELECT f.*, 
               COALESCE(NULLIF(f.doc_type, ''), d.doc_type, '') AS doc_type,
               COALESCE(NULLIF(f.doc_type, ''), d.doc_type, '') AS document,
               d.file_path
        FROM flags f
        LEFT JOIN documents d ON f.document_id = d.id
        WHERE f.application_id = ?
        ORDER BY f.id ASC
        """,
        (application_id,)
    )
    rows = [dict(row) for row in cursor.fetchall()]
    conn.close()
    return rows


def purge_all_applications(db_path: str = DB_PATH) -> None:
    """Purges all application records, submitted documents, institutions, flags, and audit logs."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute("DELETE FROM flags")
    cursor.execute("DELETE FROM documents")
    cursor.execute("DELETE FROM applications")
    cursor.execute("DELETE FROM institutions")
    cursor.execute("DELETE FROM audit_log")
    try:
        cursor.execute("DELETE FROM sqlite_sequence WHERE name IN ('flags', 'documents', 'applications', 'institutions', 'audit_log')")
    except Exception:
        pass
    conn.commit()
    conn.close()

    upload_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "uploads")
    if os.path.exists(upload_dir):
        for fname in os.listdir(upload_dir):
            fpath = os.path.join(upload_dir, fname)
            try:
                if os.path.isdir(fpath):
                    shutil.rmtree(fpath, ignore_errors=True)
                elif os.path.isfile(fpath):
                    os.remove(fpath)
            except Exception:
                pass
