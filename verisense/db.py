def authenticate_user(username_or_email: str, password: str, db_path: str = DB_PATH) -> Optional[Dict[str, Any]]:
    """Authenticates a user against the users table in SQLite."""
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute("""
        SELECT id, username, full_name, role, email, designation, department
        FROM users
        WHERE (LOWER(username) = LOWER(?) OR LOWER(email) = LOWER(?))
          AND password = ?
    """, (username_or_email.strip(), username_or_email.strip(), password.strip()))
    row = cursor.fetchone()
    conn.close()
    if row:
        return dict(row)
    return None


