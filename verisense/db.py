"""
db.py - SQLite database layer for AICTE VeriSense.
Manages institutions, applications, documents, verification flags, audit logs,
and mock AICTE historical approval records.
"""

import os
import shutil
import sqlite3
from datetime import datetime
from typing import List, Dict, Any, Optional

DB_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "verisense.db")


def get_connection(db_path: str = DB_PATH) -> sqlite3.Connection:
    """Creates a database connection with foreign keys enabled."""
    conn = sqlite3.connect(db_path, timeout=30.0)
    try:
        conn.execute("PRAGMA journal_mode = WAL;")
    except Exception:
        pass
    conn.row_factory = sqlite3.Row  # Access columns by name: row["column_name"]
    conn.execute("PRAGMA foreign_keys = ON;")
    return conn


def init_db(db_path: str = DB_PATH) -> None:
    """Initializes all required database tables including mock AICTE history."""
    conn = get_connection(db_path)
    cursor = conn.cursor()

    cursor.executescript("""
    -- Users table (Scrutiny Officers, Admins)
    CREATE TABLE IF NOT EXISTS users (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT UNIQUE NOT NULL,
        full_name TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'Scrutiny Officer',
        created_at TEXT NOT NULL
    );

    -- Institutions submitting EoA applications
    CREATE TABLE IF NOT EXISTS institutions (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        aicte_id TEXT UNIQUE NOT NULL,
        name TEXT NOT NULL,
        state TEXT NOT NULL,
        city TEXT NOT NULL,
        address TEXT,
        created_at TEXT NOT NULL
    );

    -- EoA Applications submitted by institutions
    CREATE TABLE IF NOT EXISTS applications (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        application_no TEXT UNIQUE NOT NULL,
        institution_id INTEGER NOT NULL,
        academic_year TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'Pending Review',  -- 'Pending Review', 'Flagged', 'No issues found'
        risk_score REAL DEFAULT 0.0,
        submitted_at TEXT NOT NULL,
        FOREIGN KEY (institution_id) REFERENCES institutions (id) ON DELETE CASCADE
    );

    -- Documents uploaded for an application
    CREATE TABLE IF NOT EXISTS documents (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        application_id INTEGER NOT NULL,
        doc_type TEXT NOT NULL,  -- 'NOC', 'Affidavit', 'Faculty List', 'Land Document', 'Fire Certificate'
        file_path TEXT NOT NULL,
        file_hash TEXT,
        extracted_text TEXT,
        qr_data TEXT,
        is_tampered INTEGER DEFAULT 0,  -- 0 = No, 1 = Potential Tamper Detected
        uploaded_at TEXT NOT NULL,
        FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE
    );

    -- Validation Flags generated by Rules Engine
    -- HARD RULE: Every flag must show: issue, document, rule ID, evidence, timestamp
    CREATE TABLE IF NOT EXISTS flags (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        application_id INTEGER NOT NULL,
        document_id INTEGER,
        doc_type TEXT,
        rule_id TEXT NOT NULL,
        severity TEXT NOT NULL,          -- 'CRITICAL', 'WARNING', 'INFO'
        issue TEXT NOT NULL,
        evidence TEXT NOT NULL,
        flagged_at TEXT NOT NULL,
        FOREIGN KEY (application_id) REFERENCES applications (id) ON DELETE CASCADE,
        FOREIGN KEY (document_id) REFERENCES documents (id) ON DELETE SET NULL
    );

    -- Audit Log: Tracks who performed what action and when
    CREATE TABLE IF NOT EXISTS audit_log (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        username TEXT NOT NULL,
        action TEXT NOT NULL,
        details TEXT,
        ip_address TEXT DEFAULT '127.0.0.1',
        timestamp TEXT NOT NULL
    );

    -- AICTE Historical Database (Master records of previous EoA approvals)
    CREATE TABLE IF NOT EXISTS aicte_history (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        aicte_id TEXT UNIQUE NOT NULL,
        institution_name TEXT NOT NULL,
        approved_land_area REAL NOT NULL,
        existing_intake INTEGER NOT NULL,
        last_approval_year TEXT NOT NULL,
        address TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'Active',
        updated_at TEXT NOT NULL
    );

    -- Authority QR Code Registry (Mock database of state authority QR hashes)
    CREATE TABLE IF NOT EXISTS authority_qr_registry (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        qr_payload TEXT UNIQUE NOT NULL,
        issuer_authority TEXT NOT NULL,
        document_ref TEXT NOT NULL,
        institution_name TEXT NOT NULL,
        valid_until TEXT,
        status TEXT NOT NULL DEFAULT 'VERIFIED',
        registered_at TEXT NOT NULL
    );
    """)

    try:
        cursor.execute("PRAGMA table_info(flags)")
        f_cols = [r["name"] for r in cursor.fetchall()]
        if "doc_type" not in f_cols:
            cursor.execute("ALTER TABLE flags ADD COLUMN doc_type TEXT")
    except Exception:
        pass

    # Add review columns to applications if they don't exist yet
    try:
        cursor.execute("PRAGMA table_info(applications)")
        a_cols = [r["name"] for r in cursor.fetchall()]
        if "reviewed_by" not in a_cols:
            cursor.execute("ALTER TABLE applications ADD COLUMN reviewed_by TEXT")
        if "reviewed_at" not in a_cols:
            cursor.execute("ALTER TABLE applications ADD COLUMN reviewed_at TEXT")
        if "officer_comments" not in a_cols:
            cursor.execute("ALTER TABLE applications ADD COLUMN officer_comments TEXT")
    except Exception:
        pass

    conn.commit()
    conn.close()

    # Automatically ensure default test history records, QR registry, and users exist
    seed_mock_aicte_history(db_path)
    seed_mock_qr_registry(db_path)
    seed_users(db_path)


