def get_aicte_history(aicte_id: str, db_path: str = DB_PATH) -> Optional[Dict[str, Any]]:
    """Retrieves official historical approval record for an AICTE Permanent ID."""
    if not aicte_id:
        return None
    clean_id = aicte_id.strip()
    conn = get_connection(db_path)
    cursor = conn.cursor()
    cursor.execute("SELECT * FROM aicte_history WHERE TRIM(aicte_id) = ? OR aicte_id = ?", (clean_id, clean_id))
    row = cursor.fetchone()
    conn.close()
    return dict(row) if row else None


